# grammar-engine - tool: writes the catalogue of the rules of every delivered language (docs/RULES.md).
# The identifier, category and confidence come from the @rule marks, the description from the docstring of the rule
# (the part before the first "->" is the wrong text, the part after it the corrected text), the message from the table
# of messages of the language.
#
#   python tools/list_rules.py > docs/RULES.md
#
# SPDX-License-Identifier: MIT

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from grammar_engine import Checker

LANGUAGES = [('fr', 'French'), ('en', 'English'), ('es', 'Spanish'), ('es-AR', 'Argentine Spanish (adds to Spanish)')]
HEADER = ['| Identifier | Category | Confidence | What it reports | Message |', '|---|---|---|---|---|']


def cell(text):
    """Text for a table cell: no pipe, no line break."""
    return ' '.join(text.split()).replace('|', '\\|')


def describe(fn):
    """The docstring of a rule on one line."""
    return cell(fn.__doc__ or '')


def rows(grammar, only_prefix=None, skip_any=True):
    """The table rows of the rules of a grammar, sorted by identifier."""
    out = []
    for fn, rid, category, confidence, emits in grammar._rules:
        if only_prefix and not rid.startswith(only_prefix):
            continue
        if skip_any and rid.startswith('any.'):
            continue
        ids = '`%s`' % rid + ''.join(', `%s`' % e for e in emits if e != rid)
        out.append((rid, '| %s | %s | %.2f | %s | %s |' % (ids, category, confidence, describe(fn), cell(grammar.message('en', rid)))))
    return [line for _, line in sorted(out)]


def main():
    out = ['# Catalogue of the rules', '',
           'Generated by `tools/list_rules.py` from the `@rule` marks, the docstrings and the messages of the languages. '
           '`confidence` is the default one: a rule may report a lower value for a doubtful case. '
           'Where a rule lists several identifiers it may report each of them. The examples go from the wrong text to the corrected text. '
           'Most of the rules need the lexicon of their language (`fr.lex`, `en.lex`, `es.lex`); the ones which need the spelling dictionary of the host '
           '(`known`) are `fr.participle` and `fr.infinitive`.', '']
    for code, title in LANGUAGES:
        grammar = Checker(code).grammar
        out += ['## %s (`%s`)' % (title, code), ''] + HEADER + rows(grammar, 'es_ar.' if code == 'es-AR' else None) + ['']
    out += ['## Any language (`any`)', '', 'These rules are in the base class: every language has them.', ''] + HEADER
    out += rows(Checker('xx').grammar, skip_any=False) + ['']
    sys.stdout.reconfigure(encoding='utf-8')
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
